REMOVE_INDEXES = {
    104, 144, 148, 163, 167, 180, 184, 192, 198, 204, 217, 221, 225, 229, 233, 237, 241, 247, 251, 255, 259, 263
}


def clear_and_set(paragraph, text: str) -> None:
    while paragraph.runs:
        paragraph._element.remove(paragraph.runs[0]._element)
    paragraph.add_run(text)


def remove_paragraph(paragraph) -> None:
    element = paragraph._element
    element.getparent().remove(element)


def main() -> None:
    doc = docx.Document(str(DOC_PATH))

    for idx, text in REWRITE.items():
        if idx < len(doc.paragraphs):
            clear_and_set(doc.paragraphs[idx], text)

    for idx in sorted(REMOVE_INDEXES, reverse=True):
        if idx < len(doc.paragraphs):
            remove_paragraph(doc.paragraphs[idx])

    doc.save(str(DOC_PATH))
    print(DOC_PATH)


if __name__ == "__main__":
    main()
