def remove_paragraph(paragraph):
    p = paragraph._element
    p.getparent().remove(p)


def replace_paragraph(paragraph, text: str):
    for run in list(paragraph.runs):
        paragraph._element.remove(run._element)
    paragraph.add_run(text)


def match_prefix(text: str, prefix: str) -> bool:
    return text.strip().startswith(prefix)


doc = docx.Document(str(DOC_PATH))

# Replace or remove targeted paragraphs.
for paragraph in list(doc.paragraphs):
    text = paragraph.text.strip()
    if not text:
        continue
    replaced = False
    for prefix, new_text in REPLACEMENTS.items():
        if match_prefix(text, prefix):
            replace_paragraph(paragraph, new_text)
            replaced = True
            break
    if replaced:
        continue
    for prefix in REMOVE_PREFIXES:
        if match_prefix(text, prefix):
            remove_paragraph(paragraph)
            break

# Tighten paragraph spacing and alignment.
for para in doc.paragraphs:
    text = para.text.strip()
    fmt = para.paragraph_format
    style_name = para.style.name if para.style else ""
    if text.startswith("图 ") or text.startswith("表 "):
        para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        fmt.space_before = Pt(2)
        fmt.space_after = Pt(4)
        fmt.line_spacing = 1.0
    elif text.startswith(("第一章", "第二章", "第三章", "第四章", "第五章", "第六章")):
        fmt.space_before = Pt(6)
        fmt.space_after = Pt(6)
    elif text.startswith(("1.", "2.", "3.", "4.", "5.", "6.")) or "章小结" in text:
        fmt.space_before = Pt(4)
        fmt.space_after = Pt(3)
    elif style_name.lower().startswith("heading"):
        fmt.space_before = Pt(4)
        fmt.space_after = Pt(4)
    else:
        fmt.space_before = Pt(0)
        fmt.space_after = Pt(2)
        fmt.line_spacing = 1.25

# Resize and center figure paragraphs by caption.
shape_idx = 0
image_paragraphs = []
for i, para in enumerate(doc.paragraphs):
    has_graphic = any("graphicData" in run._element.xml for run in para.runs)
    if has_graphic and i + 1 < len(doc.paragraphs):
        caption = doc.paragraphs[i + 1].text.strip()
        image_paragraphs.append((para, caption))

for para, caption in image_paragraphs:
    if shape_idx >= len(doc.inline_shapes):
        break
    shape = doc.inline_shapes[shape_idx]
    for key, width_in in FIGURE_WIDTHS.items():
        if caption.startswith(key):
            ratio = shape.height / shape.width if shape.width else 1
            shape.width = Inches(width_in)
            shape.height = int(shape.width * ratio)
            break
    para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    para.paragraph_format.space_before = Pt(2)
    para.paragraph_format.space_after = Pt(2)
    shape_idx += 1

doc.save(str(DOC_PATH))
